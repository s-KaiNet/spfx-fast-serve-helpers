import { existsSync, readFileSync } from 'node:fs';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { EOL } from 'node:os';
import path from 'node:path';
import { glob } from 'tinyglobby';
import type { Logger } from '../logger.js';
import { createHeftTerminal, createProjectLoader, heftErrorMessage, loadHeftConfiguration } from '../utils/heftProject.js';
import { isInside } from '../utils/paths.js';

const TYPINGS_LABEL = 'Static asset typings';
const CONFIG_FILE = 'config/static-asset-typings.json';
const SCHEMA = '@rushstack/heft-static-asset-typings-plugin/lib/schemas/resource-static-asset-typings.schema.json';

const ASSET_TYPINGS = [
  '// This file was generated by a tool. Modifying it will produce unexpected behavior',
  '',
  '/**',
  ' * @public',
  ' */',
  'declare const content: string;',
  'export default content;',
  '',
].join(EOL);

interface StaticAssetTypingsConfiguration {
  fileExtensions: string[];
  generatedTsFolders?: string[];
  sourceFolderPath?: string;
}

interface ResolvedConfiguration {
  sourceFolder: string;
  typingsFolders: string[];
  fileExtensions: string[];
}

export interface AssetTypings {
  generateAll(): Promise<void>;
  fileAdded(file: string): Promise<void>;
  fileRemoved(file: string): Promise<void>;
}

export interface AssetTypingsOptions {
  root: string;
  logger: Logger;
}

export function createAssetTypings({ root, logger }: AssetTypingsOptions): AssetTypings {
  let configuration: Promise<ResolvedConfiguration | undefined> | undefined;

  const ready = () =>
    (configuration ??= loadConfiguration(root, logger).catch((error: unknown) => {
      logger.warn(`${TYPINGS_LABEL} are not generated: ${heftErrorMessage(error)}`);
      return undefined;
    }));

  const typingsFiles = ({ sourceFolder, typingsFolders }: ResolvedConfiguration, asset: string) =>
    typingsFolders.map((folder) => path.join(folder, `${path.relative(sourceFolder, asset)}.d.ts`));

  const isAsset = ({ sourceFolder, fileExtensions }: ResolvedConfiguration, file: string) =>
    isInside(sourceFolder, file) && fileExtensions.some((extension) => file.endsWith(extension));

  async function writeTypings(resolved: ResolvedConfiguration, asset: string): Promise<void> {
    const outdated = typingsFiles(resolved, asset).filter((typingsFile) => !existsSync(typingsFile) || readFileSync(typingsFile, 'utf8') !== ASSET_TYPINGS);
    await Promise.all(
      outdated.map(async (typingsFile) => {
        await mkdir(path.dirname(typingsFile), { recursive: true });
        await writeFile(typingsFile, ASSET_TYPINGS);
      }),
    );
  }

  async function guarded(task: (resolved: ResolvedConfiguration) => Promise<void>): Promise<void> {
    const resolved = await ready();
    if (!resolved) return;
    try {
      await task(resolved);
    } catch (error) {
      logger.error(`${TYPINGS_LABEL}: ${heftErrorMessage(error)}`);
    }
  }

  return {
    generateAll: () =>
      guarded(async (resolved) => {
        const assets = await glob(
          resolved.fileExtensions.map((extension) => `**/*${extension}`),
          { cwd: resolved.sourceFolder, absolute: true, expandDirectories: false },
        );
        await Promise.all(assets.map((asset) => writeTypings(resolved, path.resolve(asset))));
      }),
    fileAdded: (file) =>
      guarded(async (resolved) => {
        const asset = path.resolve(file);
        if (isAsset(resolved, asset)) await writeTypings(resolved, asset);
      }),
    fileRemoved: (file) =>
      guarded(async (resolved) => {
        const asset = path.resolve(file);
        if (!isAsset(resolved, asset)) return;
        await Promise.all(typingsFiles(resolved, asset).map((typingsFile) => rm(typingsFile, { force: true })));
      }),
  };
}

async function loadConfiguration(root: string, logger: Logger): Promise<ResolvedConfiguration | undefined> {
  const load = createProjectLoader(root);
  const configuration = await loadHeftConfiguration<StaticAssetTypingsConfiguration>(root, load, createHeftTerminal(logger, TYPINGS_LABEL), {
    projectRelativeFilePath: CONFIG_FILE,
    jsonSchemaObject: load(SCHEMA) as object,
    propertyInheritance: { fileExtensions: { inheritanceType: 'append' } },
  });
  if (!configuration || configuration.fileExtensions.length === 0) return undefined;
  return {
    sourceFolder: path.resolve(root, configuration.sourceFolderPath ?? 'src'),
    typingsFolders: (configuration.generatedTsFolders ?? ['temp/static-asset-ts']).map((folder) => path.resolve(root, folder)),
    fileExtensions: configuration.fileExtensions,
  };
}
